"""Generates the repetitive XML of the GRV6 skin: skin.xml, main.xml, browse.xml, sampler_page.xml, settings.xml, loop_size.xml.
Run:  python tools/build_skin.py
Everything else in GRV6/ is hand-written. The generated files are the real skin files; this script only exists
so the deck stacks (5 pages each, page index = deck number) are not typed by hand 12 times."""
import os
