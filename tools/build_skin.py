OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "GRV6")
LEFT, RIGHT = "[Skin],grv6_left_deck", "[Skin],grv6_right_deck"


def write(name, text):
    with open(os.path.join(OUT, name), "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def dummy():
    return '<WidgetGroup><ObjectName>Transparent</ObjectName><Layout>vertical</Layout><SizePolicy>me,me</SizePolicy><Children/></WidgetGroup>'


def tpl(src, channel):
    return f'<Template src="skin:{src}"><SetVariable name="channel">{channel}</SetVariable></Template>'


def stack(control, valid, size, page):
    """A WidgetStack whose page index is the value of `control`.
    valid = deck numbers allowed on this side (page 0 and the other side's decks are empty pages).
    page(deck) returns the XML of the page for that deck."""
    pages = [page(i) if i in valid else dummy() for i in range(5)]
    body = "\n          ".join(pages)
    return (f'<WidgetStack currentpage="{control}">\n        <Size>{size}</Size>\n        <Children>\n          '
            f'{body}\n        </Children>\n      </WidgetStack>')


def other(deck):
    return {1: 3, 3: 1, 2: 4, 4: 2}[deck]


