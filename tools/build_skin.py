# ---------------------------------------------------------------- colour schemes
def theme_qss(folder, mode, accent):
    """GRV6/style.qss is written for Dark Orange; every scheme's stylesheet is it with the colours swapped
    (tools/themes.py) and the pictures taken from the scheme's own folder. rgb() colours are left alone - the accent
    swatches on the Settings tab use them on purpose."""
    with open(os.path.join(OUT, "style.qss"), encoding="utf-8") as f:
        qss = f.read()
    colours = qss_colour_map(mode, accent)
    qss = re.sub(r"#[0-9a-fA-F]{6}\b", lambda m: colours.get(m.group(0).lower(), m.group(0)), qss)
    qss = qss.replace("skin:/images/", f"skin:/images/{folder}/")
    header = f"/* GENERATED by tools/build_skin.py from style.qss - colour scheme {folder}. Edit style.qss instead. */"
    return header + "\n" + qss


def schemes_xml():
    """Mixxx skin colour schemes, one per theme + accent. Mixxx loads the one named in [Config],Scheme (the Settings
    tab's THEME / ACCENT COLOUR set it and reload the skin), else the first. Each adds its stylesheet to the skin and
    sets the variables the templates use (tools/themes.py xml_variables: picture folder, accent colours, waveform
    colours, track-colour tints)."""
    items = []
    for name, folder, mode, accent in schemes():
        variables = "".join("\n      " + f'<SetVariable name="{k}">{v}</SetVariable>'
                            for k, v in xml_variables(mode, accent).items())
        items.append(f'''    <Scheme>
      <Name>{name}</Name>
      <Style src="skin:themes/{folder}.qss"/>{variables}
    </Scheme>''')
    return "  <Schemes>\n" + "\n".join(items) + "\n  </Schemes>\n"


def write_themes():
    os.makedirs(os.path.join(OUT, "themes"), exist_ok=True)
    for _, folder, mode, accent in schemes():
        write(os.path.join("themes", folder + ".qss"), theme_qss(folder, mode, accent))


