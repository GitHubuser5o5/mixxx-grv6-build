# ---------------------------------------------------------------- sampler page
def sampler_xml():
    def row(first):
        pads = "\n".join(f'                <Template src="skin:sampler.xml"><SetVariable name="sampler">{n}</SetVariable></Template>'
                         for n in range(first, first + 8))
        return f'''          <WidgetGroup>
            <ObjectName>Transparent</ObjectName>
            <Layout>horizontal</Layout>
            <SizePolicy>me,me</SizePolicy>
            <Children>
{pads}
            </Children>
          </WidgetGroup>'''

    def heading(control, valid, first):
        def page(d):
            return ('<WidgetGroup><ObjectName>Transparent</ObjectName><Layout>horizontal</Layout><SizePolicy>me,me</SizePolicy><Children>'
                    f'<Label><ObjectName>SamplerHeading</ObjectName><Text>DECK {d}  &#183;  SAMPLERS {first}-{first + 7}</Text></Label></Children></WidgetGroup>')

        def nopage():
            return ('<WidgetGroup><ObjectName>Transparent</ObjectName><Layout>horizontal</Layout><SizePolicy>me,me</SizePolicy><Children>'
                    f'<Label><ObjectName>SamplerHeading</ObjectName><Text>SAMPLERS {first}-{first + 7}</Text></Label></Children></WidgetGroup>')
        pages = "\n          ".join(page(i) if i in valid else nopage() for i in range(5))
        return (f'<WidgetStack currentpage="{control}">\n          <Size>0me,40f</Size>\n          <Children>\n          {pages}\n'
                f'          </Children>\n        </WidgetStack>')

    def side(control, valid, first):
        return f'''      <WidgetGroup>
        <ObjectName>SamplerSide</ObjectName>
        <Layout>vertical</Layout>
        <SizePolicy>me,me</SizePolicy>
        <Children>
        {heading(control, valid, first)}
{row(first)}
        </Children>
      </WidgetGroup>'''

    return f'''<!DOCTYPE template>
<!-- GENERATED by tools/build_skin.py - Sampler page. Top row = samplers 1-8 (decks 1/3), bottom row = 9-16 (decks 2/4). Not designed yet. -->
<Template>
  <WidgetGroup>
    <ObjectName>SamplerPage</ObjectName>
    <Layout>vertical</Layout>
    <SizePolicy>me,me</SizePolicy>
    <Children>
{side(LEFT, (1, 3), 1)}
{side(RIGHT, (2, 4), 9)}
    </Children>
  </WidgetGroup>
</Template>
'''


# ---------------------------------------------------------------- settings page
def settings_xml():
    """Settings tab: four columns, eight numbered groups (06 is APPEARANCE instead of the dropped VU sensitivity).
    The [GRV6] controls are the stable 3 build's Settings backend (patches/grv6-settings-system.patch).
    Docs: docs/skin-inventory.md.

    Heights are explicit: Mixxx's layouts hand spare height to whatever might grow, which stretched the cards, so every
    block and card has a fixed height (sums are kept by the helpers, `(xml, height)` pairs) and only the cards the design
    lets grow ("flex") take the rest of the column.

    Patterns (a skin button can only write 1, and pressing a lit segment must not do anything, so a live segment is a
    WidgetStack with one page per value of the setting: the lit page is a plain label, every other page is a button):
      seg()     - one cell of a pick-one bar          switch()  - on/off switch, a 2-state push button with pictures
      stepper() - minus / value / plus (action buttons) chip()   - preset button, lit while the four decks match
      pick()    - a whole pick-one bar for a value control 0..n-1 (WidgetStack page triggers, see below)"""
    BAR = 56            # height of every bar, stepper, chip, switch and button
    PAD = 16            # card padding, and the gap between the blocks of a card
    TIGHT = 8           # gap inside a block and between neighbours (rows, chips, bands, columns)

    def size(w, h):
        return f'<Size>{w},{h}</Size>'

    def group(oname, layout, *children, sz=None, policy="me,me"):
        s = size(*sz) if sz else f'<SizePolicy>{policy}</SizePolicy>'
        return (f'<WidgetGroup><ObjectName>{oname}</ObjectName><Layout>{layout}</Layout>{s}<Children>'
                + "".join(children) + '</Children></WidgetGroup>')

    def label(text, oname, sz=None, policy="me,me"):
        s = size(*sz) if sz else f'<SizePolicy>{policy}</SizePolicy>'
        return f'<Label><ObjectName>{oname}</ObjectName><Text>{text}</Text>{s}</Label>'

    def spacer():
        return '<Label><ObjectName>Spacer</ObjectName><SizePolicy>me,me</SizePolicy></Label>'

    def gap(w, h):
        return f'<Label><ObjectName>Spacer</ObjectName><Size>{w},{h}</Size></Label>'

    def vcenter(xml, w):
        return group("Transparent", "vertical", spacer(), xml, spacer(), sz=(f"{w}f", "0me"))

    def stack(control, pages, sz=None):
        s = size(*sz) if sz else '<SizePolicy>me,me</SizePolicy>'
        return f'<WidgetStack currentpage="{control}">{s}<Children>' + "".join(pages) + '</Children></WidgetStack>'

    def push(oname, text, controls, sz=None):
        """Momentary button: writes 1 to each action push button in `controls` on press."""
        s = size(*sz) if sz else '<SizePolicy>me,me</SizePolicy>'
        acts = "".join(f'<Connection><ConfigKey>{c}</ConfigKey><EmitOnDownPress>true</EmitOnDownPress>'
                       '<ConnectValueToWidget>false</ConnectValueToWidget></Connection>' for c in controls)
        return (f'<PushButton><ObjectName>{oname}</ObjectName>{s}<NumberStates>2</NumberStates>'
                '<LeftClickIsPushButton>true</LeftClickIsPushButton>'
                f'<State><Number>0</Number><Text>{text}</Text></State><State><Number>1</Number><Text>{text}</Text></State>'
                f'{acts}</PushButton>')

    def flip(oname, text, control):
        """Button on a skin toggle control (0/1): a press flips it."""
        return (f'<PushButton><ObjectName>{oname}</ObjectName><SizePolicy>me,me</SizePolicy><NumberStates>2</NumberStates>'
                f'<State><Number>0</Number><Text>{text}</Text></State><State><Number>1</Number><Text>{text}</Text></State>'
                f'<Connection><ConfigKey>{control}</ConfigKey><EmitOnDownPress>true</EmitOnDownPress></Connection>'
                '</PushButton>')

    IMG = '<Variable name="img"/>'   # this colour scheme's picture folder (skin.xml <Schemes>)

    def pick(control, texts, trig, oname="SetSegBar", cell=None):
        """Pick-one bar for a value control (0..n-1) - no script needed. A WidgetStack whose current page IS the
        control's value; on page p the p-th cell is lit and every other cell i is a button that writes 1 to page i's
        trigger ([Skin],<trig><i>), which switches the stack, and the stack writes the new page number into
        `control` (the same mechanism as the tab buttons). cell(i, text, lit) can draw custom cells."""
        pages = []
        for p in range(len(texts)):
            cells = []
            for i, t in enumerate(texts):
                if cell:
                    cells.append(cell(i, t, i == p))
                else:
                    cells.append(label(t, "SetSegOn") if i == p else push("SetSegOff", t, [f"[Skin],{trig}{i}"]))
            pages.append(f'<WidgetGroup trigger="[Skin],{trig}{p}"><ObjectName>{oname}</ObjectName>'
                         '<Layout>horizontal</Layout><SizePolicy>me,me</SizePolicy><Children>'
                         + "".join(cells) + '</Children></WidgetGroup>')
        return (f'<WidgetStack currentpage="{control}"><Size>0me,{BAR}f</Size><Children>' + "".join(pages)
                + '</Children></WidgetStack>')

    def visible_group(control, inner, negate=False, sz=None):
        t = "<Transform><Not/></Transform>" if negate else ""
        s = size(*sz) if sz else '<SizePolicy>me,me</SizePolicy>'
        return ('<WidgetGroup><ObjectName>Transparent</ObjectName><Layout>stacked</Layout>' + s +
                f'<Connection><ConfigKey>{control}</ConfigKey>{t}<BindProperty>visible</BindProperty></Connection>'
                f'<Children>{inner}</Children></WidgetGroup>')

    # ---- building blocks; parts are (xml, height) ---------------------------------------------------------------------
    def seg(control, npages, active, text, button):
        pages = [label(text, "SetSegOn") if i == active else button for i in range(npages)]
        return stack(control, pages)

    def bar(*cells):
        return group("SetSegBar", "horizontal", *cells, sz=("0me", f"{BAR}f"))

    def block(name, body, body_h, hint=None, header_extra=None):
        head_items = [label(name, "SetGroupLabel")] + (header_extra or [])
        items = [group("SetGroupRow", "horizontal", *head_items, sz=("0me", "18f")), body]
        h = 18 + 8 + body_h
        if hint:
            items.append(label(hint, "SetHint", sz=("0me", "18f")))
            h += 8 + 18
        return group("SetGroup", "vertical", *items, sz=("0me", f"{h}f")), h

    def switch(control):
        return ('<PushButton><ObjectName>SetSwitch</ObjectName><Size>104f,56f</Size><NumberStates>2</NumberStates>'
                f'<State><Number>0</Number><Unpressed>{IMG}/sw_off.png</Unpressed><Pressed>{IMG}/sw_off.png</Pressed></State>'
                f'<State><Number>1</Number><Unpressed>{IMG}/sw_on.png</Unpressed><Pressed>{IMG}/sw_on.png</Pressed></State>'
                f'<Connection><ConfigKey>{control}</ConfigKey><EmitOnDownPress>true</EmitOnDownPress></Connection>'
                '</PushButton>')

    def switch_row(name, hint, control):
        text = group("SetGroup", "vertical", spacer(), label(name, "SetGroupLabel", sz=("0me", "18f")),
                     *([label(hint, "SetHint", sz=("0me", "18f"))] if hint else []), spacer())
        return group("SetGroupRow", "horizontal", text, switch(control), sz=("0me", f"{BAR}f")), BAR

    def stepper(minus, val, plus):
        return group("SetStep", "horizontal", minus, val, plus, sz=("0me", f"{BAR}f"))

    def chip(text, targets, actions, w):
        """Preset: writes `actions`; lit while [ChannelN],orientation == targets[N-1] for all four decks."""
        def level(i):
            pages = []
            for v in range(3):
                if v != targets[i]:
                    pages.append(push("SetChip", text, actions))
                else:
                    pages.append(label(text, "SetChipOn") if i == 3 else level(i + 1))
            return stack(f"[Channel{i + 1}],orientation", pages)
        return group("Transparent", "horizontal", level(0), sz=(f"{w}f", f"{BAR}f"))

    def card(num, title, parts, flex=False):
        head = group("SetCardHead", "horizontal", label(num, "SetCardNum", sz=("34f", "20f")),
                     label(title, "SetCardTitle"), sz=("0me", "20f"))
        body = [head] + [x for x, _ in parts] + ([spacer()] if flex else [])
        # The card's inner margins are fixed-size empty labels: qproperty-layoutContentsMargins is ignored by Mixxx's
        # widget groups (see SKIN-NOTES), spacers are not.
        inner = group("SetCardBody", "vertical", *body)
        middle = group("Transparent", "horizontal", gap(f"{PAD}f", "0me"), inner, gap(f"{PAD}f", "0me"))
        h = PAD + 20 + sum(PAD + ph for _, ph in parts) + PAD + 2      # +2: the card's own 1 px border
        top, bottom = gap("0me", f"{PAD}f"), gap("0me", f"{PAD}f")
        if flex:
            return group("SetCard", "vertical", top, middle, bottom)
        return group("SetCard", "vertical", top, middle, bottom, sz=("0me", f"{h}f"))

    def column(*cards, sz=None):
        return group("SetCol", "vertical", *cards, sz=sz)

    # ---- 01 mixer -------------------------------------------------------------------------------------------------
    eq_slot = "[OutputEffectRack_[Master]_Effect1]"

    def band(name, params):
        conns = "".join(f'<Connection><ConfigKey>{eq_slot},parameter{n}</ConfigKey></Connection>' for n in params)
